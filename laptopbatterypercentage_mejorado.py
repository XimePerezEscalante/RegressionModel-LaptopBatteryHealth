def fit_standardize(X):
    means = X.mean()
    stds = X.std()

    return means, stds


def transform_standardize(X, means, stds):

    X_scaled = X.copy()

    for column in X.columns:
        X_scaled[column] = (
            X[column] - means[column]
        ) / stds[column]

    return X_scaled

