"""
Funcion de hipotesis
Calcula la prediccion
por cada parametro.
input:
    params: parametros
    x_row: fila del arreglo de X
output:
    y_pred: y (prediccion)
"""


def hyp(params, x_row):

    y_pred = params[0]

    for j in range(1, len(params)):
        y_pred += params[j] * x_row[j - 1]

    return y_pred

"""
Funcion de Prediccion
Aplica la hipotesis a cada fila del arreglo X.
"""
def predict_all(params, X):
    predicciones = []

    for i in range(len(X)):
        predicciones.append(hyp(params, X[i]))

    return np.array(predicciones)

"""
Funcion de costo - Mean Squared Error (MSE)
"""
def mse(params, X, Y_real):

    acum = 0.0
    n = len(X)

    for i in range(n):
        y_pred = hyp(params, X[i])
        acum += (y_pred - Y_real[i]) ** 2

    return acum / n

"""
Funcion de optimizacion - Gradiente Descendiente
"""
def grad_desc(params, X, Y_real, alpha):
    params = np.array(params, dtype=float)
    n = len(X)

    gradients = np.zeros(len(params))

    errors = np.zeros(n)

    for i in range(n):
        errors[i] = hyp(params, X[i]) - Y_real[i]

    for j in range(len(params)):

        acum = 0.0
        for i in range(n):
            if j == 0:
                acum += errors[i] * 1
            else:
                acum += errors[i] * X[i][j - 1]

        gradients[j] = (1 / n) * acum

    new_params = params - alpha * gradients

    return new_params

def optimize(max_epochs, og_parameters, X, Y, alpha, X_val, Y_val):
    params = np.array(og_parameters, dtype=float)

    loss_array = []
    theta_array = []
    val_loss_array = []

    for epoch in range(max_epochs + 1):

        params = grad_desc(params, X, Y, alpha)
        theta_array.append(params.copy())

        loss = mse(params, X, Y)
        loss_array.append(loss)

        val_loss = mse(params, X_val, Y_val)
        val_loss_array.append(val_loss)

        if epoch % 100 == 0 or epoch == max_epochs:
            print(
                f"Epoch {epoch}: Loss = {loss:}    Val Loss = {val_loss:}")

    print("\nFin de la optimizacion")

    return params, loss_array, theta_array, val_loss_array

"""
    Función del coeficiente de determinacion
    R2 = 1 - SS_res / SS_tot
    Proporcion de la varianza de la target variable explicada por el modelo.
    """
def r2(y_true, y_pred):
    n = len(y_true)

    suma = 0
    for i in range(n):
        suma += y_true[i]
    media = suma / n

    ss_res = 0
    ss_tot = 0
    for i in range(n):
        ss_res += (y_true[i] - y_pred[i]) ** 2
        ss_tot += (y_true[i] - media) ** 2

    return 1.0 - ss_res / ss_tot

